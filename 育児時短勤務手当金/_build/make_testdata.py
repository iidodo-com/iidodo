"""架空のテストデータ入り電子申請書を作る。 python make_testdata.py form.xlsx 出力先ディレクトリ"""
import sys, openpyxl
src, outdir = sys.argv[1], sys.argv[2]


def make(month, req_day, slip_comm, name):
    wb = openpyxl.load_workbook(src)
    ws, ky = wb["入力"], wb["給与明細"]
    base = {"C6": 9000001, "D7": 8, "F7": month, "C9": "999", "F9": "000001", "C10": "シケン　ハナコ", "C11": "試験　花子", "C12": "女",
            "C13": "平成", "D13": 2, "F13": 3, "H13": 15, "C15": "テスト課", "C16": "広島市中区国泰寺町1-6-34",
            "C18": "育児短時間勤務", "C19": "2回目以降", "D20": 8, "F20": 4, "H20": 1, "D21": 9, "F21": 3, "H21": 31,
            "C25": "試験　一郎", "D26": 7, "F26": 10, "H26": 1, "C29": "有",
            "D37": 8, "F37": month + 1, "H37": req_day, "C38": "試験　花子", "C39": "090-0000-0000", "C40": "庶務　太郎", "C41": "81-0000",
            "C43": "✓", "C44": "✓", "C45": "✓", "C46": "✓", "C54": 22, "C55": 300000}
    for a, v in base.items():
        ws[a] = v
    ky_vals = {"B15": 190000, "C15": 15200, "E15": 12000, "F15": slip_comm, "C17": 4100,
               "B23": 3200, "C23": 12000, "D23": 11500, "E23": 250, "F23": 21000, "G23": 1720, "H23": 1820, "I23": 1233, "B29": 3200, "C29": 33,
               "C32": "数か月分一括支給", "D33": 8, "F33": 4, "C34": 18900, "D35": 8, "F35": 4, "D36": 8, "F36": 6}
    for a, v in ky_vals.items():
        ky[a] = v
    wb.save(f"{outdir}/{name}.xlsx")


make(4, 10, 18900, "test4")   # 支給月（明細に一括の通勤手当あり）
make(5, 8, 0, "test5")        # 2か月目（明細に通勤手当なし）
